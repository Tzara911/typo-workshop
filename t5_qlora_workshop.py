def symspell_post(text: str) -> str:
   # Use SymSpell to fix any leftover spelling issues after model output
    suggestions = sym_spell.lookup_compound(
        text,             # full sentence to correct
        max_edit_distance_lookup=2,   # allow up to 2 edits
        transfer_casing=True      # preserve original capitalization
    )
    # Return best correction if available, else return original
    return suggestions[0].term if suggestions else text


# 5. Define final typo‑correction function with SymSpell fallback
def correct_typo(text, max_tokens=64):
    inp_text = rules + f"\nfix: {text}"
    inp = tokenizer(inp_text, return_tensors="pt", padding=True,truncation=False ).to(full_model.device)
     # Run model inference to generate corrected output
    out = full_model.generate(
         input_ids=inp["input_ids"],
            attention_mask=inp["attention_mask"],
            max_new_tokens=max_tokens,
            num_beams=5,
            no_repeat_ngram_size=2,
            early_stopping=True,
            repetition_penalty=1.2,
            do_sample=False
    )
    result = tokenizer.decode(out[0], skip_special_tokens=True)
     # Final SymSpell pass to catch any stray typos
    sug = sym_spell.lookup_compound(result, 2, True)

 # Use SymSpell suggestion if available; otherwise fall back to model output
    if sug:
        return sug[0].term
    else:
        return result

