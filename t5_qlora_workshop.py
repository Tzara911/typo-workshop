"""#  Data Augmentation via SymSpell Typos
 This block introduces artificial spelling mistakes into your dataset by randomly replacing a word in each sentence with a plausible typo using the SymSpell dictionary.

**Goal**: Enrich the training set with realistic noisy inputs for typo correction.
- Start from clean corrected_text
- Introduce 1 typo per sentence (based on frequency-based edits) - Append typo→corrected pairs back to dataset for fine-tuning
"""

augmented = []  # collect augmented examples
for ex in raw_ds:
    clean = ex["corrected_text"]
    words = clean.split()
    idx = random.randrange(len(words))

    # Use SymSpell to generate a possible typo of the selected word
    suggestions = sym_spell.lookup(
        words[idx],
        Verbosity.TOP,
        max_edit_distance)

    # Ensure the suggestion is a valid (but incorrect) typo
    if suggestions and suggestions[0].term != words[idx]:
        typo = words.copy()
        typo[idx] = suggestions[0].term
        augmented.append({
            "text": " ".join(typo),
            "corrected_text": clean
        })
# Wrap augmented examples
