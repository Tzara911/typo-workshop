"""#Step 8:  NoiseStopCallback: Custom Early-Stopping Strategy
This class defines a custom Hugging Face Trainer callback that stops training early when the average change in training loss becomes very small—indicating convergence.

**Purpose:**
 1. Avoid overfitting by stopping training once learning has plateaued
 2. Speed up fine-tuning by skipping unnecessary extra steps
 3. Replace the need for a validation set in low-resource or fast demo settings

**Method:**
 1. Accumulate training loss values logged by the Trainer
 2. Once `min_steps` have passed, start checking loss stability
 3. Calculate the average loss delta over the last `window` logging steps
 4. If the average delta is below the `threshold`, training stops automatically

**Parameters:**
 1. `threshold`: how small the change in loss must be to count as “stable” (e.g. 0.002)
 2. `window`: how many recent losses to include when calculating change
 3. `min_steps`: don't monitor loss until this many steps have passed

**Result:**
 Training ends early when the model stops learning meaningfully—saving time and resources.


"""

class NoiseStopCallback(TrainerCallback):
    def __init__(
        self,
        threshold=0.002,
        window=10,
        min_steps=200
      ):

        self.losses = []
        self.threshold = threshold
        self.window = window
        self.min_steps = min_steps

    def on_log(self, args, state: TrainerState, control: TrainerControl, logs=None, **kwargs):
      # 1) Record the current loss from logs
        loss = logs.get("loss")
        if loss is None:
            return control
        self.losses.append(loss)

       # 2) Do not evaluate stopping condition until after min_steps
        if state.global_step < self.min_steps:
            return control

        # 3) Once enough losses are recorded, calculate average Δloss
        if len(self.losses) >= self.window:
            recent = self.losses[-self.window:]   # take the most recent `window` losses
             # compute absolute delta between each consecutive pair
            deltas = [abs(recent[i] - recent[i-1]) for i in range(1, len(recent))]
            avg_delta = sum(deltas) / len(deltas)
       # 4) If average delta is below threshold, trigger early stop
            if avg_delta < self.threshold:
                print(f">>> Stop by noise at step {state.global_step}: avgΔ={avg_delta:.6f} < {self.threshold}")
                control.should_training_stop = True

        return control

